// term is the terminal backend the Manager drives. The real one runs
// tmux inside a sandbox; tests use a scripted fake.
type term interface {
	// create opens shell name. It returns errExists if tmux already has it.
	create(ctx context.Context, name string) error
	// send types line into the shell, after writing cmd to cmdPath, then
	// polls like poll.
	send(ctx context.Context, name, cmdPath, cmd, line string, p pollSpec) (pollResult, error)
	// poll waits up to p.wait for the shell's log to grow past p.off and
	// returns what was appended.
	poll(ctx context.Context, name string, p pollSpec) (pollResult, error)
	interrupt(ctx context.Context, name string) error
	// respawn restarts a dead shell's bash in the same pane.
	respawn(ctx context.Context, name string) error
	kill(ctx context.Context, name string) error
	// list returns the open shells and their log sizes.
	list(ctx context.Context) (map[string]int64, error)
	// cmdPath is where the command for shell name is written.
	cmdPath(name string) string
}

var (
	errExists = errors.New("tmux session exists")
	errGone   = errors.New("tmux session is gone")
)

type pollSpec struct {
	off  int64
	wait time.Duration
	// mark is the done-marker prefix of the running command, or "". The
	// poll returns as soon as it appears.
	mark string
}

type paneState int

const (
	paneAlive paneState = iota
	paneDead
	paneGone
)

type pollResult struct {
	// from is the log offset data starts at. It is greater than the
	// requested offset when a large backlog was skipped.
	from int64
	data []byte
	// skippedDone is the done marker found in the skipped backlog, if any.
	skippedDone string
	state       paneState
	// status is the exit status of a dead pane's shell.
	status int
}

// Poll tuning. The in-sandbox loop checks the log every pollTick, returns
// streamWait after output first appears (so live output reaches the UI
// in about a quarter second), and reads at most readMax bytes. A backlog
// over skipMax is skipped down to its last keepTail bytes: the model only
// sees a tail anyway.
const (
	pollTick   = 25 * time.Millisecond
	streamWait = 250 * time.Millisecond
	readMax    = 256 << 10
	skipMax    = 4 << 20
	keepTail   = 256 << 10
	// inlineCmdMax is the largest command sent inline (base64 in the exec
	// command line); bigger ones are written with WriteFile first.
	inlineCmdMax = 48 << 10
)

// sbTerm runs tmux in a sandbox through sandbox.Exec.
type sbTerm struct {
	sb     sandbox.Sandbox
	dir    string // per-sandbox state dir: rc file, logs, commands
	socket string // tmux -L socket name
	user   string
}

const sessionPrefix = "k-"

func (t *sbTerm) session(name string) string { return sessionPrefix + name }
func (t *sbTerm) logPath(name string) string { return t.dir + "/" + name + ".log" }
func (t *sbTerm) cmdPath(name string) string { return t.dir + "/" + name + ".cmd" }
func (t *sbTerm) tmux() string               { return "tmux -L " + sbutil.Quote(t.socket) }
func (t *sbTerm) target(name string) string  { return sbutil.Quote("=" + t.session(name) + ":") }

// rcFile is the bash rc every shell starts with. PROMPT_COMMAND prints the
// done marker for the command whose ID is in __KEITH_ID; it is exported
// (with its function) so a nested bash keeps working. Prompts are empty so
// they don't pollute output.
const rcFile = `# Generated by Keith (internal/sandbox/tmuxshell).
[ -f ~/.bashrc ] && . ~/.bashrc
PS1='' PS2='' PS4='+ '
HISTCONTROL=ignorespace
bind 'set enable-bracketed-paste off' 2>/dev/null
__keith_done() { local rc=$?; if [ -n "${__KEITH_ID-}" ]; then printf '__KEITH_D_%s_%d__\n' "$__KEITH_ID" "$rc"; __KEITH_ID=; fi; return $rc; }
export -f __keith_done
PROMPT_COMMAND=__keith_done
export PROMPT_COMMAND
`

// Exit codes of the create script.
const (
	exitNoTmux = 93
	exitExists = 94
)

func (t *sbTerm) bashCmd() string {
	return sbutil.Quote("exec bash --rcfile " + t.dir + "/rc -i")
}

func (t *sbTerm) run(ctx context.Context, script string, timeout time.Duration) (*sandbox.ExecResult, error) {
	return t.sb.Exec(ctx, sandbox.ExecRequest{Cmd: script, Dir: "/", Timeout: timeout, User: t.user}, nil)
}

func (t *sbTerm) create(ctx context.Context, name string) error {
	d := sbutil.Quote(t.dir)
	sess := sbutil.Quote(t.session(name))
	script := strings.Join([]string{
		"command -v tmux >/dev/null 2>&1 || { echo 'tmux is not installed in the sandbox' >&2; exit " + strconv.Itoa(exitNoTmux) + "; }",
		"command -v bash >/dev/null 2>&1 || { echo 'bash is not installed in the sandbox' >&2; exit " + strconv.Itoa(exitNoTmux) + "; }",
		"mkdir -p " + d + " && chmod 700 " + d + " || exit 1",
		"printf %s " + sbutil.Quote(base64.StdEncoding.EncodeToString([]byte(rcFile))) + " | base64 -d > " + d + "/rc || exit 1",
		t.tmux() + " has-session -t " + sbutil.Quote("="+t.session(name)) + " 2>/dev/null && exit " + strconv.Itoa(exitExists),
		": > " + sbutil.Quote(t.logPath(name)),
		t.tmux() + " new-session -d -s " + sess + " -x 200 -y 50 -c " + sbutil.Quote(sandbox.WorkspaceDir) + " " + t.bashCmd() +
			` \; set-option -w -t ` + t.target(name) + ` remain-on-exit on` +
			` \; pipe-pane -o -t ` + t.target(name) + " " + sbutil.Quote("cat >> "+sbutil.Quote(t.logPath(name))),
	}, "\n")
	res, err := t.run(ctx, script, 30*time.Second)
	if err != nil {
		return err
	}
	switch res.ExitCode {
	case 0:
		return nil
	case exitExists:
		return errExists
	default:
		return fmt.Errorf("tmuxshell: create shell %q: exit %d: %s", name, res.ExitCode, strings.TrimSpace(res.Stderr+res.Stdout))
	}
}

// pollScript is the bash code shared by send and poll. The wait loop is
// bounded by wall time ($EPOCHREALTIME, bash 5), not a tick count, so
// fork overhead in a slow sandbox doesn't stretch it.
func (t *sbTerm) pollScript(name string, p pollSpec) string {
	f := sbutil.Quote(t.logPath(name))
	mark := sbutil.Quote(p.mark)
	var markRE string
	if p.mark != "" {
		markRE = sbutil.Quote(p.mark + "[0-9]+__")
	} else {
		markRE = "''"
	}
	return fmt.Sprintf(`f=%s; off=%d; mark=%s; g=0
n=${EPOCHREALTIME/[.,]/}; n=${n:-$((SECONDS * 1000000))}
end=$(( n + %d ))
while :; do
  s=$(stat -c %%s "$f" 2>/dev/null || echo 0)
  n=${EPOCHREALTIME/[.,]/}; n=${n:-$((SECONDS * 1000000))}
  if (( s > off )); then
    (( s - off >= %d )) && break
    if [[ -n $mark ]] && tail -c +$((off + 1)) "$f" | grep -aqF -e "$mark"; then break; fi
    (( g == 0 )) && g=$n
    (( n - g >= %d )) && break
  fi
  (( n >= end )) && break
  sleep %s
done
st=$(%s display-message -p -t %s '#{pane_dead} #{pane_dead_status}' 2>/dev/null) || st=gone
s=$(stat -c %%s "$f" 2>/dev/null || echo 0)
from=$off; sk=
(( s < off )) && from=0
if (( s - from > %d )); then
  nf=$((s - %d))
  [[ -n $mark ]] && sk=$(tail -c +$((from + 1)) "$f" | head -c $((nf - from)) | grep -aoE -e %s | head -n 1)
  from=$nf
fi
printf '%%s|%%s|%%s\n' "$st" "$from" "${sk:--}"
tail -c +$((from + 1)) "$f" 2>/dev/null | head -c %d | base64
`, f, p.off, mark, p.wait.Microseconds(), readMax, streamWait.Microseconds(),
		strconv.FormatFloat(pollTick.Seconds(), 'f', -1, 64),
		t.tmux(), t.target(name), skipMax, keepTail, markRE, readMax)
}

// bash wraps a bash script for sandbox.Exec, which runs sh -c.
func bash(script string) string { return "exec bash -c " + sbutil.Quote(script) }

func (t *sbTerm) poll(ctx context.Context, name string, p pollSpec) (pollResult, error) {
	res, err := t.run(ctx, bash(t.pollScript(name, p)), p.wait+30*time.Second)
	if err != nil {
		return pollResult{}, err
	}
	return parsePoll(res, p.off)
}

func (t *sbTerm) send(ctx context.Context, name, cmdPath, cmd, line string, p pollSpec) (pollResult, error) {
	var b strings.Builder
	if len(cmd) <= inlineCmdMax {
		fmt.Fprintf(&b, "printf %%s %s | base64 -d > %s || exit 1\n",
			sbutil.Quote(base64.StdEncoding.EncodeToString([]byte(cmd))), sbutil.Quote(cmdPath))
	} else if err := t.sb.WriteFile(ctx, cmdPath, []byte(cmd), 0o600); err != nil {
		return pollResult{}, fmt.Errorf("tmuxshell: write command: %w", err)
	}
	fmt.Fprintf(&b, "%s send-keys -t %s -l %s \\; send-keys -t %s Enter 2>/dev/null || { echo 'gone|0|-'; exit 0; }\n",
		t.tmux(), t.target(name), sbutil.Quote(line), t.target(name))
	b.WriteString(t.pollScript(name, p))
	res, err := t.run(ctx, bash(b.String()), p.wait+30*time.Second)
	if err != nil {
		return pollResult{}, err
	}
	return parsePoll(res, p.off)
}

// parsePoll decodes the poll script's output: a header line
// "<pane_dead> <status>|<from>|<skipped marker or ->" (or "gone|...")
// followed by the base64 of the new log bytes.
func parsePoll(res *sandbox.ExecResult, off int64) (pollResult, error) {
	if res.ExitCode != 0 {
		return pollResult{}, fmt.Errorf("tmuxshell: poll: exit %d: %s", res.ExitCode, strings.TrimSpace(res.Stderr))
	}
	header, body, _ := strings.Cut(res.Stdout, "\n")
	parts := strings.SplitN(header, "|", 3)
	if len(parts) != 3 {
		return pollResult{}, fmt.Errorf("tmuxshell: poll: malformed header %q", header)
	}
	pr := pollResult{from: off}
	st := strings.Fields(parts[0])
	switch {
	case len(st) == 0 || st[0] == "gone":
		pr.state = paneGone
		return pr, nil
	case st[0] == "1":
		pr.state = paneDead
		if len(st) > 1 {
			pr.status, _ = strconv.Atoi(st[1])
		}
	}
	from, err := strconv.ParseInt(parts[1], 10, 64)
	if err != nil {
		return pollResult{}, fmt.Errorf("tmuxshell: poll: malformed offset %q", parts[1])
	}
	pr.from = from
	if parts[2] != "-" {
		pr.skippedDone = parts[2]
	}
	clean := bytes.Map(func(r rune) rune {
		if r == '\n' || r == '\r' || r == ' ' {
			return -1
		}
		return r
	}, []byte(body))
	pr.data = make([]byte, base64.StdEncoding.DecodedLen(len(clean)))
	n, err := base64.StdEncoding.Decode(pr.data, clean)
	if err != nil {
		return pollResult{}, fmt.Errorf("tmuxshell: poll: decode output: %w", err)
	}
	pr.data = pr.data[:n]
	return pr, nil
}

func (t *sbTerm) interrupt(ctx context.Context, name string) error {
	res, err := t.run(ctx, t.tmux()+" send-keys -t "+t.target(name)+" C-c", 30*time.Second)
	if err != nil {
		return err
	}
	if res.ExitCode != 0 {
		return errGone
	}
	return nil
}

func (t *sbTerm) respawn(ctx context.Context, name string) error {
	tg := t.target(name)
	res, err := t.run(ctx, t.tmux()+" respawn-pane -k -t "+tg+" -c "+sbutil.Quote(sandbox.WorkspaceDir)+" "+t.bashCmd()+
		` \; pipe-pane -t `+tg+` \; pipe-pane -o -t `+tg+" "+sbutil.Quote("cat >> "+sbutil.Quote(t.logPath(name))), 30*time.Second)
	if err != nil {
		return err
	}
	if res.ExitCode != 0 {
		return fmt.Errorf("tmuxshell: respawn shell %q: %s", name, strings.TrimSpace(res.Stderr))
	}
	return nil
}

func (t *sbTerm) kill(ctx context.Context, name string) error {
	_, err := t.run(ctx, t.tmux()+" kill-session -t "+sbutil.Quote("="+t.session(name))+" 2>/dev/null; rm -f "+
		sbutil.Quote(t.logPath(name))+" "+sbutil.Quote(t.cmdPath(name)), 30*time.Second)
	return err
}

func (t *sbTerm) list(ctx context.Context) (map[string]int64, error) {
	script := t.tmux() + ` list-sessions -F '#{session_name}' 2>/dev/null | while read -r s; do
  case "$s" in ` + sessionPrefix + `*) n=${s#` + sessionPrefix + `}; echo "$n $(stat -c %s ` + sbutil.Quote(t.dir) + `/"$n".log 2>/dev/null || echo 0)";; esac
done`
	res, err := t.run(ctx, script, 30*time.Second)
	if err != nil {
		return nil, err
	}
	out := map[string]int64{}
	for _, line := range strings.Split(strings.TrimSpace(res.Stdout), "\n") {
		name, size, ok := strings.Cut(line, " ")
		if !ok {
			continue
		}
		n, _ := strconv.ParseInt(size, 10, 64)
		out[name] = n
	}
	return out, nil
}
